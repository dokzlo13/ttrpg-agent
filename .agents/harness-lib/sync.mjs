// Adapter generation. Every file written here is an OUTPUT: it carries a
// do-not-edit header and `verify` regenerates it into a temp tree and diffs.
// Change the canonical source or this generator — never the emitted file.

import fs from "node:fs";
import path from "node:path";

export const BANNER = "GENERATED by .agents/harness sync — do not edit. Source: ";

const collected = [];

function record(rel, contents) {
  collected.push({ rel, contents });
}

export function planned() {
  return collected.slice();
}

export function resetPlan() {
  collected.length = 0;
}

// ---------------------------------------------------------------------------
// helpers

function mdBanner(source) {
  return `<!-- ${BANNER}${source} -->\n`;
}

function shBanner(source) {
  return `# ${BANNER}${source}\n`;
}

function jsBanner(source) {
  return `// ${BANNER}${source}\n`;
}

function readBody(root, name) {
  return fs.readFileSync(path.join(root, ".agents/prompts", `${name}.md`), "utf8");
}

// Canonical bodies use pi's argument token. Rewrite it for Claude, including
// the backticked form used in prose. Anchored so a stray `$@` inside a shell
// example would also be caught — none exist today, and if one is ever added it
// should be escaped in the canonical body rather than silently mistranslated.
function claudeArgs(body) {
  return body.replace(/\$@/g, "$ARGUMENTS");
}

function yamlString(value) {
  // Always quote: descriptions contain colons, quotes and brackets.
  return JSON.stringify(String(value));
}

function tierModel(manifest, tier, harness) {
  if (!tier) return undefined;
  const entry = manifest.tiers?.[tier];
  if (!entry) throw new Error(`unknown model tier: ${tier}`);
  return entry[harness];
}

function effortLevel(manifest, effort, harness) {
  if (!effort) return undefined;
  const entry = manifest.effort?.[effort];
  if (!entry) throw new Error(`unknown effort level: ${effort}`);
  return entry[harness];
}

