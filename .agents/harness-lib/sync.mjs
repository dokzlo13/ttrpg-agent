// creative-brainstorm chain: four artifacts from one spec

function candidateSchema(spec) {
  const props = {};
  for (const field of spec.candidateFields) {
    props[field] =
      field === "risks"
        ? { type: "array", minItems: 1, items: { type: "string" } }
        : { type: "string" };
  }
  return {
    type: "object",
    additionalProperties: false,
    required: ["candidates"],
    properties: {
      candidates: {
        type: "array",
        minItems: spec.candidatesMin,
        maxItems: spec.candidatesMax,
        items: {
          type: "object",
          additionalProperties: false,
          required: spec.candidateFields.slice(),
          properties: props,
        },
      },
    },
  };
}

function lensTask(spec, lens) {
  return [
    "CREATIVE BRIEF",
    "{task}",
    "",
    `ASSIGNED LENS — ${lens.title}`,
    `${lens.brief} Generate ${spec.candidatesMin}–${spec.candidatesMax} candidates and return only the required structured output.`,
  ].join("\n");
}

export function genChain(root, manifest) {
  for (const entry of manifest.chain ?? []) {
    const spec = JSON.parse(fs.readFileSync(path.join(root, entry.spec), "utf8"));
    const schema = candidateSchema(spec);

    // --- pi chain JSON ---
    const chain = {
      _generated: `${BANNER}${entry.spec}`,
      name: spec.name,
      description: spec.description,
      chain: [
        {
          phase: "Divergence",
          label: "Four creative lenses",
          parallel: spec.lenses.map((lens) => ({
            agent: spec.personas.ideator.name,
            as: lens.id,
            skill: false,
            reads: false,
            progress: false,
            task: lensTask(spec, lens),
            outputSchema: schema,
            acceptance: false,
          })),
          concurrency: spec.concurrency,
          failFast: false,
          worktree: false,
        },
        {
          agent: spec.personas.curator.name,
          phase: "Curation",
          label: "Diverse shortlist",
          skill: false,
          reads: false,
          progress: false,
          task: [
            "CREATIVE BRIEF",
            "{task}",
            "",
            ...spec.lenses.flatMap((lens) => [
              `ANONYMIZED CANDIDATE BATCH ${lens.id.replace(/^batch_/, "").toUpperCase()}`,
              `{outputs.${lens.id}}`,
              "",
            ]),
            spec.curatorTask,
          ].join("\n"),
          acceptance: false,
        },
      ],
    };
    record(`.pi/chains/${spec.name}.chain.json`, JSON.stringify(chain, null, 2) + "\n");

    // --- pi agent personas ---
    for (const persona of [spec.personas.ideator, spec.personas.curator]) {
      const fm = [
        "---",
        `name: ${persona.name}`,
        // Quoted: spec.json is hand-edited, and a description containing ": "
        // makes the generated frontmatter unparseable YAML.
        `description: ${yamlString(persona.description)}`,
        `model: ${tierModel(manifest, persona.tier, "pi")}`,
        `thinking: ${effortLevel(manifest, persona.effort, "pi")}`,
        // Preserve pi's exact tool contract.
        `tools: ${persona.structuredOutput ? "structured_output" : "none"}`,
        "extensions:",
        "systemPromptMode: replace",
        "inheritProjectContext: false",
        "inheritSkills: false",
        "defaultContext: fresh",
        "maxSubagentDepth: 0",
        "completionGuard: false",
        "---",
        "",
      ].join("\n");
      record(
        `.pi/agents/${persona.name}.md`,
        fm + mdBanner(entry.spec) + "\n" + persona.body + "\n",
      );
    }

    // --- Claude workflow ---
    // Prose contains {braces}; every embedded string goes through
    // JSON.stringify so the emitted JS cannot be corrupted by the content.
    const js = [
      jsBanner(entry.spec),
      "",
      "export const meta = {",
      `  name: ${JSON.stringify(spec.name)},`,
      `  description: ${JSON.stringify(spec.description)},`,
      "  phases: [",
      '    { title: "Divergence", detail: "four isolated lenses, in parallel" },',
      '    { title: "Curation", detail: "one curator over the anonymized pool" },',
      "  ],",
      "};",
      "",
      `const IDEATOR = ${JSON.stringify(spec.personas.ideator.body)};`,
      `const CURATOR = ${JSON.stringify(spec.personas.curator.body)};`,
      `const SCHEMA = ${JSON.stringify(schema, null, 2)};`,
      `const LENSES = ${JSON.stringify(
        spec.lenses.map((l) => ({ id: l.id, title: l.title, task: lensTask(spec, l) })),
        null,
        2,
      )};`,
      "",
      "// `args` is the creative brief. The main agent is expected to have gathered",
      "// and verified the relevant context already and to pass a self-contained brief.",
      "const brief = typeof args === \"string\" ? args : (args?.task ?? \"\");",
      "if (!brief.trim()) {",
      '  throw new Error("creative-brainstorm needs a self-contained brief as args");',
      "}",
      "",
      "phase(\"Divergence\");",
      "const batches = await parallel(",
      "  LENSES.map((lens) => () =>",
      "    agent(`${IDEATOR}\\n\\n${lens.task.replace(\"{task}\", brief)}`, {",
      "      label: `lens:${lens.id}`,",
      '      phase: "Divergence",',
      "      schema: SCHEMA,",
      `      effort: ${JSON.stringify(effortLevel(manifest, spec.personas.ideator.effort, "claude"))},`,
      "    }),",
      "  ),",
      ");",
      "",
      "// A barrier is correct here: the curator's whole job is cross-candidate",
      "// comparison, so it genuinely needs every lens's output at once.",
      "phase(\"Curation\");",
      "const pool = LENSES.map((lens, i) => {",
      "  const out = batches[i];",
      "  const label = lens.id.replace(/^batch_/, \"\").toUpperCase();",
      "  return `ANONYMIZED CANDIDATE BATCH ${label}\\n${JSON.stringify(out ?? { candidates: [] }, null, 2)}`;",
      "}).join(\"\\n\\n\");",
      "",
      "const shortlist = await agent(",
      "  [CURATOR, \"\", \"CREATIVE BRIEF\", brief, \"\", pool, \"\", " +
        JSON.stringify(spec.curatorTask) + "].join(\"\\n\"),",
      "  {",
      '    label: "curator",',
      '    phase: "Curation",',
      `    effort: ${JSON.stringify(effortLevel(manifest, spec.personas.curator.effort, "claude"))},`,
      "  },",
      ");",
      "",
      "return shortlist;",
      "",
    ].join("\n");
    record(`.claude/workflows/${spec.name}.js`, js);
  }
}

