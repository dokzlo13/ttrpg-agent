// skills: .claude/skills/<name> -> symlink into .agents/skills/<name>

export function skillNames(root) {
  const dir = path.join(root, ".agents/skills");
  return fs
    .readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isDirectory() && fs.existsSync(path.join(dir, e.name, "SKILL.md")))
    .map((e) => e.name)
    .sort();
}

export function syncClaudeSkills(root, { apply }) {
  const names = skillNames(root);
  const dir = path.join(root, ".claude/skills");
  if (apply) fs.mkdirSync(dir, { recursive: true });

  const results = [];
  for (const name of names) {
    const link = path.join(dir, name);
    const target = path.relative(dir, path.join(root, ".agents/skills", name));
    let state = "relinked";
    if (fs.existsSync(link) || fs.lstatSync(link, { throwIfNoEntry: false })) {
      const st = fs.lstatSync(link, { throwIfNoEntry: false });
      if (st && !st.isSymbolicLink()) {
        // Refuse to clobber a real directory — that would destroy hand-written
        // content that someone put in the wrong place.
        results.push({ name, state: "REFUSED (not a symlink)" });
        continue;
      }
      if (st && fs.readlinkSync(link) === target) state = "unchanged";
    } else {
      state = "created";
    }
    if (apply && state !== "unchanged") {
      // unlink, not rm: rmSync follows the symlink, so it throws EISDIR when
      // the link points at a directory (an absolute-path link from an older
      // sync) and silently succeeds without unlinking when the link dangles.
      try {
        fs.unlinkSync(link);
      } catch (error) {
        if (error.code !== "ENOENT") throw error;
      }
      fs.symlinkSync(target, link);
    }
    results.push({ name, state });
  }

  // Remove stale symlinks for skills that no longer exist.
  if (fs.existsSync(dir)) {
    for (const entry of fs.readdirSync(dir)) {
      if (names.includes(entry)) continue;
      const p = path.join(dir, entry);
      if (fs.lstatSync(p).isSymbolicLink()) {
        if (apply) {
          try {
            fs.unlinkSync(p);
          } catch (error) {
            if (error.code !== "ENOENT") throw error;
          }
        }
        results.push({ name: entry, state: "removed (stale)" });
      } else {
        // A real file/dir sitting where a generated symlink belongs. Never
        // delete it — say so, and let verify fail.
        results.push({ name: entry, state: "REFUSED (not a symlink, and not a known skill)" });
      }
    }
  }
  return results;
}

// ---------------------------------------------------------------------------
// prompts

// pi: the canonical body is CONCATENATED, not referenced. A "read and follow
// .agents/prompts/x.md" stub would downgrade pi from a guaranteed inlined body
// to an instruction the model may under-execute — a reliability regression on
// destructive commands like /cleanup.
export function genPiPrompts(root, manifest) {
  for (const p of manifest.prompt ?? []) {
    const fm = [
      "---",
      `name: ${p.name}`,
      `description: ${yamlString(p.description)}`,
    ];
    if (p.argument_hint) fm.push(`argument-hint: ${yamlString(p.argument_hint)}`);
    const effort = effortLevel(manifest, p.effort, "pi");
    if (effort) fm.push(`thinking: ${effort}`);
    const model = tierModel(manifest, p.tier, "pi");
    if (model) fm.push(`model: ${model}`);
    // pi's `skill:` is a guaranteed preload. Preserve it exactly.
    if (p.skill) fm.push(`skill: ${p.skill}`);
    fm.push("---", "");

    const body = readBody(root, p.name);
    record(`.pi/prompts/${p.name}.md`, fm.join("\n") + mdBanner(`.agents/prompts/${p.name}.md`) + "\n" + body);
  }
}

// Claude: the body is CONCATENATED, same as pi's, for two reasons.
//
//   1. `$@` is pi's argument token and Claude's is `$ARGUMENTS`. An @-import
//      inlines the canonical body *verbatim*, so the rewrite is impossible —
//      a literal `$@` would ship through to the model. That is not cosmetic:
//      /cleanup's body says "determine the intended scope from the user's
//      input" immediately after a line reading `User input: $@`.
//   2. `skill:` has no Claude equivalent, so we emit an explicit preload
//      preamble ahead of the body.
//
// Concatenating gives the same guaranteed-inline property @-import had, and
// lets the substitution actually happen.
export function genClaudeCommands(root, manifest) {
  for (const p of manifest.prompt ?? []) {
    const fm = ["---", `description: ${yamlString(p.description)}`];
    if (p.argument_hint) fm.push(`argument-hint: ${yamlString(p.argument_hint)}`);
    const model = tierModel(manifest, p.tier, "claude");
    if (model) fm.push(`model: ${model}`);
    fm.push("---", "");

    const lines = [fm.join("\n"), mdBanner(`.agents/prompts/${p.name}.md`), ""];
    if (p.skill) {
      lines.push(
        `**Before doing anything else, load the \`${p.skill}\` skill and follow it.**`,
        `It is not optional and it is not background reading: this command's`,
        `correctness depends on it.`,
        "",
      );
    }
    lines.push(claudeArgs(readBody(root, p.name)));
    record(`.claude/commands/${p.name}.md`, lines.join("\n"));
  }
}

