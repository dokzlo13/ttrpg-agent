// CLAUDE.md — Claude does not load AGENTS.md on its own.

export function genClaudeMd(root, manifest) {
  const contract = manifest.project?.contract ?? "AGENTS.md";
  record(
    "CLAUDE.md",
    [
      mdBanner(".agents/manifest.toml"),
      "",
      `Claude Code does not load \`${contract}\` on its own, so this file imports it.`,
      `The project contract lives in \`${contract}\` — edit that, not this file.`,
      "",
      `@${contract}`,
      "",
    ].join("\n"),
  );
}

