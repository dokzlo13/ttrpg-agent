// Claude settings

export function genClaudeSettings(root, manifest) {
  const mcpNames = (manifest.mcp ?? []).map((m) => m.name);
  const binNames = [];
  for (const t of manifest.tool ?? []) for (const b of t.bin ?? []) binNames.push(b);
  binNames.push("qmd", "qmd-cpu");

  const settings = {
    _generated: `${BANNER}.agents/manifest.toml`,
    hooks: {
      // The env contract, applied before every Bash call. $CLAUDE_ENV_FILE is
      // supplied only to SessionStart/Setup/CwdChanged/FileChanged hooks.
      //
      // $CLAUDE_PROJECT_DIR must be expanded HERE, at hook time. Writing it
      // literally into the env file expands to empty inside the Bash tool's
      // shell — learned the hard way.
      //
      // SessionStart alone is sufficient: env.sh derives everything from
      // TTRPG_ROOT/BASH_SOURCE rather than the cwd, so changing directory
      // cannot invalidate the sourced snippet.
      // The env file is sourced by whatever shell the Bash tool uses — the
      // user's login shell. fish cannot source POSIX shell, so pick the right
      // file. (.agents/env.fish contains no duplicated logic; it transcribes
      // `TTRPG_ENV_DUMP=1 bash env.sh` and delegates qmd to .agents/bin.)
      //
      // TTRPG_ROOT is exported alongside, and that is load-bearing: Claude's
      // Bash cwd persists across calls, so after a single `cd /tmp` env.sh
      // would otherwise fall back to cwd/git discovery, declare /tmp the
      // project, and build a whole ghost skeleton there with the caches
      // repointed. $CLAUDE_PROJECT_DIR is already in hand — use it.
      //
      // $CLAUDE_PROJECT_DIR must be expanded HERE, at hook time; written
      // literally it expands to empty inside the Bash tool's shell.
      SessionStart: [
        {
          hooks: [
            {
              type: "command",
              command:
                'case "${SHELL##*/}" in ' +
                'fish) printf \'set -gx TTRPG_ROOT "%s"\\nsource "%s/.agents/env.fish"\\n\' "$CLAUDE_PROJECT_DIR" "$CLAUDE_PROJECT_DIR" >> "$CLAUDE_ENV_FILE" ;; ' +
                '*) printf \'export TTRPG_ROOT="%s"\\nsource "%s/.agents/env.sh"\\n\' "$CLAUDE_PROJECT_DIR" "$CLAUDE_PROJECT_DIR" >> "$CLAUDE_ENV_FILE" ;; ' +
                "esac",
            },
          ],
        },
      ],
    },
    enabledMcpjsonServers: mcpNames,
    permissions: {
      allow: [
        ...binNames.sort().map((b) => `Bash(.agents/bin/${b}:*)`),
        "Bash(.agents/harness:*)",
      ],
    },
  };
  record(".claude/settings.json", JSON.stringify(settings, null, 2) + "\n");
}

