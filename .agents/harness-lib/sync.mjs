export function generateAll(root, manifest) {
  resetPlan();
  genPiPrompts(root, manifest);
  genClaudeCommands(root, manifest);
  genMcpJson(root, manifest);
  genCodexConfig(root, manifest);
  genClaudeSettings(root, manifest);
  genClaudeMd(root, manifest);
  genChain(root, manifest);
  return planned();
}

// Directories whose *entire* matching contents are generated. Anything here
// that the current plan does not produce is an orphan: a renamed or deleted
// prompt/chain otherwise leaves a working /npc command behind forever, and the
// drift check (plan -> disk) cannot see it because it only walks the plan.
const GENERATED_DIRS = [
  { dir: ".claude/commands", test: (f) => f.endsWith(".md") },
  { dir: ".claude/workflows", test: (f) => f.endsWith(".js") },
  { dir: ".pi/prompts", test: (f) => f.endsWith(".md") },
  { dir: ".pi/chains", test: (f) => f.endsWith(".chain.json") },
  { dir: ".pi/agents", test: (f) => f.startsWith("creative-") && f.endsWith(".md") },
];

export function orphanedArtifacts(root, plan) {
  const produced = new Set(plan.map((p) => p.rel));
  const orphans = [];
  for (const { dir, test } of GENERATED_DIRS) {
    const abs = path.join(root, dir);
    if (!fs.existsSync(abs) || !fs.statSync(abs).isDirectory()) continue;
    for (const f of fs.readdirSync(abs)) {
      if (!test(f)) continue;
      const rel = `${dir}/${f}`;
      if (!produced.has(rel)) orphans.push(rel);
    }
  }
  return orphans.sort();
}

export function writePlan(root, plan) {
  const written = [];
  for (const { rel, contents } of plan) {
    const abs = path.join(root, rel);
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    const before = fs.existsSync(abs) ? fs.readFileSync(abs, "utf8") : null;
    if (before === contents) {
      written.push({ rel, state: "unchanged" });
      continue;
    }
    fs.writeFileSync(abs, contents);
    written.push({ rel, state: before === null ? "created" : "updated" });
  }
  return written;
}
