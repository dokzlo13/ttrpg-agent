"""``render`` — dataset to Obsidian-visible transcript chunks.

Contract (DESIGN §1, §4; PLAN step 5):

* Read turns through the SDK's ``Dataset.turns(merge_gap_s=…)`` — never a local
  re-implementation. Two turn assemblers that disagree by one merge produce
  evidence links that point at the wrong words. ``drop_bleed`` stays **off**:
  rendering keeps bleed-suspect turns and marks them, because a wrong guess
  deletes real dialogue. Extraction is the stage that drops them.
* Apply lexicon substitution at render time (the dataset stays verbatim), map
  ``user_id`` to a name through ``_speakers.yaml``, and **mark** unmapped
  speakers rather than guessing one.
* Mark bleed and overlap; split chunks on turn boundaries at roughly
  ``--window-minutes``; write ``NN-mmm-mmm.md`` lines shaped
  ``[hh:mm:ss] **Speaker**: text ^t<turnid>`` plus the ``__<id>.md`` overview.
* Write ``anchors.json`` (``segment_i -> {turn_id, chunk, t0}``) — the ID bridge
  every later stage resolves evidence through — and ``index.sqlite`` for ``grep``.
* Snapshot both ``_*.yaml`` into ``inputs/`` so a rendered transcript records the
  identity and correction data it was produced with.
* Skip-if-done on ``CompositeKey(dataset_digest, lexicon_digest, speakers_digest,
  knobs={window_minutes, merge_gap_s})``.

Two decisions worth stating where the code lives.

**Substitution is exact replacement of enumerated strings, never matching.** For
every active lexicon term, each string the owner wrote down in ``variants`` is
replaced by ``display_ru`` (or ``canonical``). One alternation regex is built
from all of them, longest first, so ``Вазагар`` cannot be clobbered by a shorter
variant nested inside it, and a replacement can never be re-matched by a later
pass. Word boundaries are Unicode ``\\w`` lookarounds, which are correct for
Cyrillic. There is deliberately no similarity, distance or fuzzy logic anywhere
in this file.

A ``morph: true`` term adds *more enumerated strings* to that same alternation —
case-paired forms generated by :mod:`session_ingest.morphs`, where both the
matched variant and its replacement were inflected to the same case, so
«Марвике» becomes «Морвике» and not «Морвика». The owner's literal entries are
inserted first and win every conflict, and the two kinds are counted separately
in the ``--json`` payload and in provenance so a substitution can always be
traced back to a line in ``_lexicon.yaml`` or to an auditable generated pair.

**The whole vault directory is rewritten atomically.** Chunk boundaries move when
``--window-minutes`` changes, so an in-place rewrite would leave chunks from the
previous layout lying beside the new ones — stale files that qmd would happily
index and an agent would happily cite. The new tree is staged in a sibling
directory and swapped in.
"""

